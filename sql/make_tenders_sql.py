#!/usr/bin/env python3
"""Generate sql/tenders.sql: typed Postgres views over the hub's `records` table (schema `eprocure`).

The crawler stores each tender's parsed fields as strings, exactly as the portal wrote them. These views cast them: dates become
timestamps, amounts become numbers, counts become integers; anything that does not parse becomes NULL instead of an error.
Run `python sql/make_tenders_sql.py > sql/tenders.sql` after changing parsing.COLUMNS, then apply with psql.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import parsing  # noqa: E402

INTS = {"no_of_covers", "bid_validity_days", "period_of_work_days", "bids_count", "qualified_bids_count", "has_boq_chart", "has_tech_summary", "priced_bidders"}
NUMS = {"tender_fee", "emd_amount", "emd_percentage", "tender_value", "awarded_value", "contract_value_aoc_total", "awarded_value_sum", "l1_bid_value"}
JSONS = {"winners", "stage_done", "date_flags"}        # kept as JSON arrays
BOOLS = {"l1_inferred"}
DATES = {"pre_bid_meeting_date", "published_date", "bid_opening_date", "bid_download_start_date", "bid_download_end_date",
         "clarification_start_date", "clarification_end_date", "bid_submission_start_date", "bid_submission_end_date", "award_date",
         "financial_bid_opening_date"}
RENAMED_DATES = {"published_date": "published_at", "bid_opening_date": "bid_opening_at", "bid_download_start_date": "bid_download_start_at",
                 "bid_download_end_date": "bid_download_end_at", "clarification_start_date": "clarification_start_at",
                 "clarification_end_date": "clarification_end_at", "bid_submission_start_date": "bid_submission_start_at",
                 "bid_submission_end_date": "bid_submission_end_at", "pre_bid_meeting_date": "pre_bid_meeting_at", "award_date": "awarded_at",
                 "financial_bid_opening_date": "financial_bid_opening_at"}


def col(c):
    src = f"r.data->'details'->'fields'->>'{c}'"
    if c in INTS:
        return f"  ({src})::int AS {c}"
    if c in NUMS:
        return f"  eprocure.num({src}) AS {c}"
    if c in DATES:
        return f"  eprocure.ts({src}) AS {RENAMED_DATES[c]}"
    if c in JSONS:
        return f"  r.data->'details'->'fields'->'{c}' AS {c}"
    if c in BOOLS:
        return f"  ({src})::boolean AS {c}"
    return f"  {src} AS {c}"


def main():
    fields = [c for c in parsing.COLUMNS if c not in ("tender_id", "org_id", "org_name")]
    print("""-- Generated by make_tenders_sql.py: do not edit by hand.
CREATE SCHEMA IF NOT EXISTS eprocure;

-- '28-May-2025 06:30 PM' or '28-May-2025' -> timestamp; anything else -> NULL
CREATE OR REPLACE FUNCTION eprocure.ts(t text) RETURNS timestamp LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  IF t IS NULL OR btrim(t) = '' THEN RETURN NULL; END IF;
  BEGIN RETURN to_timestamp(btrim(t), 'DD-Mon-YYYY HH12:MI AM')::timestamp; EXCEPTION WHEN others THEN NULL; END;
  BEGIN RETURN to_timestamp(btrim(t), 'DD-Mon-YYYY')::timestamp; EXCEPTION WHEN others THEN RETURN NULL; END;
END $$;

-- '65,870' -> 65870, 'NA' or '' -> NULL
CREATE OR REPLACE FUNCTION eprocure.num(t text) RETURNS numeric LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  RETURN NULLIF(regexp_replace(coalesce(t, ''), '[^0-9.]', '', 'g'), '')::numeric;
EXCEPTION WHEN others THEN RETURN NULL;
END $$;
""")
    print("-- dropped and recreated (not replaced) so new parser columns can sit before the window columns; nothing depends on this view")
    print("DROP VIEW IF EXISTS eprocure.tenders;")
    print("CREATE VIEW eprocure.tenders AS\nSELECT\n  r.record_id AS tender_id,\n  r.data->>'org_id' AS org_id,\n  r.data->>'org_name' AS org_name,")
    print(",\n".join(col(c) for c in fields) + ",")
    print("""  r.data->'window'->>0 AS window_from,
  r.data->'window'->>1 AS window_to,
  r.data->'details'->>'pages_key' AS pages_key,
  r.data->'details'->'procurement_details' AS procurement_details,
  r.data->'details'->'outcomes' AS commercial_outcomes,
  r.data->'details'->>'parse_error' AS parse_error,
  r.scraped_at
FROM public.records r WHERE r.project = 'eprocure-tenders';

CREATE OR REPLACE VIEW eprocure.tender_bids AS
SELECT r.record_id AS tender_id, b->>'sno' AS sno, b->>'bid_number' AS bid_number, b->>'bidder_name' AS bidder_name,
       eprocure.ts(b->>'submitted_date') AS submitted_at, b->>'status' AS status, b->>'remarks' AS remarks,
       eprocure.ts(b->>'status_updated_on') AS status_updated_at
FROM public.records r, jsonb_array_elements(r.data->'details'->'bids') b WHERE r.project = 'eprocure-tenders';

CREATE OR REPLACE VIEW eprocure.tender_documents AS
SELECT r.record_id AS tender_id, d->>'name' AS name, d->>'kind' AS kind, d->>'status' AS status, d->>'reason' AS reason,
       (d->>'declared_bytes')::bigint AS declared_bytes, (d->>'bytes')::bigint AS bytes, d->>'content_type' AS content_type,
       d->>'sha256' AS sha256, d->>'key' AS storage_key
FROM public.records r, jsonb_array_elements(r.data->'details'->'documents') d WHERE r.project = 'eprocure-tenders';

-- tenders per organisation per date window, from the planning pass
CREATE OR REPLACE VIEW eprocure.plan AS
SELECT r.data->>'org_id' AS org_id, r.data->>'org_name' AS org_name, r.data->>'from_date' AS from_date, r.data->>'to_date' AS to_date,
       (r.data->>'count')::int AS tenders
FROM public.records r WHERE r.project = 'eprocure-plan';
""")


if __name__ == "__main__":
    main()
